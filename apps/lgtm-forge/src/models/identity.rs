//! Domain model for human and AI agent identities.

use uuid::Uuid;

use crate::{
    database,
    error::{Error, Result},
    proto::lgtm::v1::IdentitySummary,
};

/// Discriminated identity details for a human user or AI agent.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum IdentityKind {
    /// Human identity requiring a valid email and optional remote forge login.
    Human {
        email: String,
        forge_login: Option<String>,
    },
    /// AI agent identity requiring a model provider and model identifier (never an email).
    Agent { provider: String, model: String },
}

/// Application actor that authors commits, review sessions, or comments.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Identity {
    pub id: Uuid,
    pub name: String,
    pub kind: IdentityKind,
}

impl Identity {
    /// Construct and validate a human identity.
    pub fn new_human(
        id: Uuid,
        name: &str,
        email: &str,
        forge_login: Option<String>,
    ) -> Result<Self> {
        let name = require_non_empty("identity.name", name)?;
        let email = require_non_empty("identity.email", email)?;
        if !email.contains('@') {
            return Err(Error::Invalid(format!(
                "human identity email '{email}' must contain '@'"
            )));
        }
        let forge_login = forge_login
            .map(|login| login.trim().to_owned())
            .filter(|login| !login.is_empty());
        Ok(Self {
            id,
            name,
            kind: IdentityKind::Human { email, forge_login },
        })
    }

    /// Construct and validate an AI agent identity.
    pub fn new_agent(id: Uuid, name: &str, provider: &str, model: &str) -> Result<Self> {
        let name = require_non_empty("identity.name", name)?;
        let provider = require_non_empty("identity.provider", provider)?;
        let model = require_non_empty("identity.model", model)?;
        Ok(Self {
            id,
            name,
            kind: IdentityKind::Agent { provider, model },
        })
    }

    // Public ------------------------------------------------------------------

    /// Convert a persisted database identity row into a domain `Identity`.
    pub fn from_db(model: database::Identity) -> Result<Self> {
        match model.kind {
            database::IdentityKind::Human => {
                let email = model.email.ok_or_else(|| {
                    Error::Invalid("persisted Human identity is missing email".to_owned())
                })?;
                Self::new_human(model.id, &model.name, &email, model.forge_login)
            }
            database::IdentityKind::Agent => {
                let provider = model.provider.ok_or_else(|| {
                    Error::Invalid("persisted Agent identity is missing provider".to_owned())
                })?;
                let model_name = model.model.ok_or_else(|| {
                    Error::Invalid("persisted Agent identity is missing model".to_owned())
                })?;
                Self::new_agent(model.id, &model.name, &provider, &model_name)
            }
        }
    }

    /// Format the Git author email used when writing local or snapshot commits.
    pub fn git_author_email(&self) -> String {
        match &self.kind {
            IdentityKind::Human { email, .. } => email.clone(),
            IdentityKind::Agent { provider, model } => {
                format!("{model}@{provider}.agent.lgtm.local")
            }
        }
    }

    /// Return the AI disclosure footer line when this identity is an `Agent`.
    pub fn agent_disclosure_footer(&self) -> Option<String> {
        match &self.kind {
            IdentityKind::Human { .. } => None,
            IdentityKind::Agent { provider, model } => Some(format!(
                "> Generated by AI agent `{provider}/{model}` via LGTM"
            )),
        }
    }
}

impl From<Identity> for IdentitySummary {
    fn from(identity: Identity) -> Self {
        match identity.kind {
            IdentityKind::Human { email, forge_login } => Self {
                id: identity.id.to_string(),
                name: identity.name,
                kind: "human".to_owned(),
                email: Some(email),
                forge_login,
                provider: None,
                model: None,
                ..Default::default()
            },
            IdentityKind::Agent { provider, model } => Self {
                id: identity.id.to_string(),
                name: identity.name,
                kind: "agent".to_owned(),
                email: None,
                forge_login: None,
                provider: Some(provider),
                model: Some(model),
                ..Default::default()
            },
        }
    }
}

fn require_non_empty(field: &str, value: &str) -> Result<String> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        return Err(Error::Invalid(format!("{field} must not be empty")));
    }
    Ok(trimmed.to_owned())
}

// tests -----------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn should_validate_human_and_agent_identities_and_format_disclosure() {
        let human = Identity::new_human(
            Uuid::new_v4(),
            "Reviewer",
            "reviewer@example.com",
            Some("reviewer".to_owned()),
        )
        .unwrap();
        assert_eq!(human.agent_disclosure_footer(), None);

        let agent = Identity::new_agent(
            Uuid::new_v4(),
            "claude-sonnet-4-5",
            "anthropic",
            "claude-sonnet-4-5",
        )
        .unwrap();
        assert_eq!(
            agent.agent_disclosure_footer().as_deref(),
            Some("> Generated by AI agent `anthropic/claude-sonnet-4-5` via LGTM")
        );
    }
}
