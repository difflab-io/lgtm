use std::collections::BTreeMap;

use lgtm_config::{LgtmConfig, MiseTaskConfig};
use serde::{Deserialize, Serialize};

use crate::error::Result;

/// Representation of the LGTM-managed `.lgtm/mise.toml` file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct GeneratedMiseFile {
    /// Tool versions synthesized from detected languages and user-configured `[tools]` in `.lgtm/mise.toml`.
    #[serde(skip_serializing_if = "BTreeMap::is_empty", default)]
    pub tools: BTreeMap<String, String>,
    /// Task definitions synthesized from detected languages and user-configured `[tasks]` in `.lgtm/mise.toml`.
    #[serde(skip_serializing_if = "BTreeMap::is_empty", default)]
    pub tasks: BTreeMap<String, MiseTaskEntry>,
}

/// A serialized task entry inside `.lgtm/mise.toml`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MiseTaskEntry {
    /// Optional human-readable description of the task.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// Working directory template for task execution (`{{cwd}}`).
    #[serde(default = "default_task_dir")]
    pub dir: String,
    /// Shell command executed when the task runs.
    pub run: String,
}

fn default_task_dir() -> String {
    "{{cwd}}".to_string()
}

/// Summary of an available Mise task exposed to CLI and UI consumers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MiseTaskSummary {
    /// Task identifier (`check`, `rust:check`, etc.).
    pub name: String,
    /// Optional human-readable task description.
    pub description: Option<String>,
    /// Shell command executed by the task.
    pub run: String,
}

impl GeneratedMiseFile {
    /// Synthesizes a `.lgtm/mise.toml` model from the merged config and detected workspace languages.
    pub fn from_config(config: &LgtmConfig, detected_languages: &[String]) -> Self {
        let mut tools = BTreeMap::new();
        let mut tasks = BTreeMap::new();

        for lang_id in detected_languages {
            if let Some(lang_cfg) = config.languages.get(lang_id) {
                if !lang_cfg.enabled {
                    continue;
                }
                if config.lsp.enabled && config.lsp.auto_install {
                    for (tool, version) in &lang_cfg.mise_tools {
                        tools.entry(tool.clone()).or_insert_with(|| version.clone());
                    }
                }
                for (task_name, task_cfg) in &lang_cfg.default_tasks {
                    let entry = Self::to_entry(task_cfg);
                    tasks
                        .entry(format!("{lang_id}:{task_name}"))
                        .or_insert_with(|| entry.clone());
                    tasks.entry(task_name.clone()).or_insert(entry);
                }
            }
        }

        Self { tools, tasks }
    }

    // Public ------------------------------------------------------------------

    /// Merges user-defined tools and tasks from an existing `.lgtm/mise.toml` file onto this model.
    pub fn merge_existing(&mut self, existing: Self) {
        for (tool, version) in existing.tools {
            self.tools.insert(tool, version);
        }
        for (task_name, entry) in existing.tasks {
            self.tasks.insert(task_name, entry);
        }
    }

    /// Serializes the generated Mise configuration to formatted TOML with an LGTM header comment.
    pub fn render_toml(&self) -> Result<String> {
        let body = toml::to_string_pretty(self)?;
        Ok(format!(
            "# Auto-generated by LGTM (.lgtm/mise.toml).\n\n{body}"
        ))
    }

    /// Returns a sorted list of task summaries for display or CLI output.
    pub fn get_task_summaries(&self) -> Vec<MiseTaskSummary> {
        self.tasks
            .iter()
            .map(|(name, entry)| MiseTaskSummary {
                name: name.clone(),
                description: entry.description.clone(),
                run: entry.run.clone(),
            })
            .collect()
    }

    // Private -----------------------------------------------------------------

    fn to_entry(cfg: &MiseTaskConfig) -> MiseTaskEntry {
        match cfg {
            MiseTaskConfig::Command(run) => MiseTaskEntry {
                description: None,
                dir: "{{cwd}}".to_string(),
                run: run.clone(),
            },
            MiseTaskConfig::Detailed { description, run } => MiseTaskEntry {
                description: description.clone(),
                dir: "{{cwd}}".to_string(),
                run: run.clone(),
            },
        }
    }
}

// tests -----------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;

    // tests -------------------------------------------------------------------

    mod given_detected_rust_and_typescript_languages {
        use super::*;

        mod when_building_generated_mise_file {
            use super::*;

            #[test]
            fn should_synthesize_tools_and_default_tasks_deterministically() {
                // Arrange
                let config = LgtmConfig::default();
                let detected = vec!["rust".to_string(), "typescript".to_string()];
                let existing: GeneratedMiseFile = toml::from_str(
                    "[tasks.hello]\ndescription = \"Greet workspace\"\nrun = \"echo hello\"\n",
                )
                .unwrap();

                // Act
                let mut generated = GeneratedMiseFile::from_config(&config, &detected);
                generated.merge_existing(existing);
                let rendered = generated.render_toml().unwrap();

                // Assert
                assert_eq!(
                    generated.tools.get("rust-analyzer"),
                    Some(&"latest".to_string())
                );
                assert_eq!(
                    generated.tools.get("npm:typescript-language-server"),
                    Some(&"latest".to_string())
                );
                assert_eq!(
                    generated.tasks.get("rust:check").map(|t| t.run.as_str()),
                    Some("cargo check")
                );
                assert_eq!(
                    generated
                        .tasks
                        .get("typescript:check")
                        .map(|t| t.run.as_str()),
                    Some("tsc --noEmit")
                );
                assert_eq!(
                    generated.tasks.get("hello").map(|t| t.run.as_str()),
                    Some("echo hello")
                );
                assert!(rendered.starts_with("# Auto-generated by LGTM (.lgtm/mise.toml)."));
            }
        }
    }
}
